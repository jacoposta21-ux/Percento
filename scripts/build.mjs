// Builds dist/: copies the static app and writes dist/src/data.js.
// --mode=production serves verified entries only; --mode=dev serves all
// entries (with review mode and a banner).
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadEntries, ROOT, argValue } from './lib/data.mjs';

const mode = argValue('mode', 'production');
const out = join(ROOT, argValue('out', 'dist'));
const KEEP = ['id', 'text', 'detail', 'emoji', 'value', 'source', 'sourceUrl', 'year', 'category', 'tone', 'status',
  'addedOn', 'verifiedOn', 'country', 'reviewReason'];

const all = loadEntries();
const entries = (mode === 'production' ? all.filter((e) => e.status === 'verified') : all)
  .map((e) => Object.fromEntries(KEEP.filter((k) => e[k] !== undefined && (mode === 'dev' || k !== 'reviewReason')).map((k) => [k, e[k]])))
  .sort((a, b) => (a.id < b.id ? -1 : 1));

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'src'), { recursive: true });
cpSync(join(ROOT, 'index.html'), join(out, 'index.html'));
cpSync(join(ROOT, 'styles.css'), join(out, 'styles.css'));
cpSync(join(ROOT, 'privacy.html'), join(out, 'privacy.html'));
cpSync(join(ROOT, 'vendor'), join(out, 'vendor'), { recursive: true });
for (const f of ['app.js', 'config.js', 'pairs.js', 'daily.js', 'dial.js', 'storage.js', 'share.js', 'copy.js', 'online.js', 'online-config.js', 'audio.js', 'icons.js', 'i18n.js', 'modes.js']) {
  cpSync(join(ROOT, 'src', f), join(out, 'src', f));
}
const build = { mode, builtOn: new Date().toISOString().slice(0, 10), count: entries.length };
writeFileSync(join(out, 'src', 'data.js'),
  `// Generated by scripts/build.mjs. Do not edit.\nexport const BUILD = ${JSON.stringify(build)};\nexport const ENTRIES = ${JSON.stringify(entries)};\n`);
console.log(`built ${out} (${mode}): ${entries.length} entries`);

// Translations: interface strings as they are, card texts only for the cards in this build.
cpSync(join(ROOT, 'src', 'locales'), join(out, 'src', 'locales'), { recursive: true });
mkdirSync(join(out, 'src', 'cards'), { recursive: true });
const i18nDir = join(ROOT, 'data', 'i18n');
for (const file of existsSync(i18nDir) ? readdirSync(i18nDir).filter((f) => f.endsWith('.json')) : []) {
  const all = JSON.parse(readFileSync(join(i18nDir, file), 'utf8'));
  const cards = Object.fromEntries(entries.filter((e) => all[e.id]).map((e) => [e.id, all[e.id]]));
  writeFileSync(join(out, 'src', 'cards', file.replace('.json', '.js')),
    `// Generated by scripts/build.mjs from data/i18n/${file}. Do not edit.\nexport default ${JSON.stringify(cards)};\n`);
}
