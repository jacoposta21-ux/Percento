// Generates DATA_REVIEW.md: every unverified entry with its reason, a seeded
// random 10% sample of verified entries for a human spot-check (PDF sources
// first), and the log of sources that could not be opened.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { loadEntries, ROOT } from './lib/data.mjs';
import { CATEGORIES } from '../src/config.js';
import { mulberry32, hashString } from '../src/pairs.js';

const entries = loadEntries();
const log = existsSync(join(ROOT, 'data', 'verification-log.json'))
  ? JSON.parse(readFileSync(join(ROOT, 'data', 'verification-log.json'), 'utf8'))
  : {};
const verified = entries.filter((e) => e.status === 'verified');
const unverified = entries.filter((e) => e.status === 'unverified');
const approved = entries.filter((e) => e.status === 'approved');
// Approved entries play in production but were never checked against their source page.
const unchecked = entries.filter((e) => e.status !== 'verified');
const code = (e) => e.reviewReason.split(':')[0];
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const link = (e) => `[${esc(e.source)}](${e.verifiedUrl || e.sourceUrl})${e.pdf ? ' (PDF)' : ''}`;

function sample(list, share, seed) {
  const rng = mulberry32(hashString(seed));
  const shuffled = [...list].sort((a, b) => (a.id < b.id ? -1 : 1))
    .map((e) => [rng(), e]).sort((a, b) => a[0] - b[0]).map(([, e]) => e);
  const n = Math.max(1, Math.ceil(list.length * share));
  // PDF sources are the easiest to misread, so they go first.
  return [...shuffled.filter((e) => e.pdf), ...shuffled.filter((e) => !e.pdf)].slice(0, n);
}

const out = [];
out.push('# DATA_REVIEW', '');
out.push(`Generated by \`npm run review\`. Entries: ${entries.length} total, **${verified.length} verified**, ${approved.length} approved by the founder, ${unverified.length} unverified.`, '');
out.push('Production serves verified and founder-approved entries. Approved means the founder read the card and accepted it in a review, without opening the source page, so every entry below is still worth a `npm run verify-sources` run.', '');

out.push('## Why nothing is verified yet', '');
out.push('The dataset was researched in a build environment whose network policy blocked every statistics website:',
  'the shell could reach only package registries and the page fetcher could not resolve any host. Each candidate was',
  'therefore taken from **search excerpts restricted to the official source domain**, with the exact wording quoted in',
  '`evidence`. That is not "opening the source", so under the data rules every entry stays `unverified`.', '',
  'To promote entries, run from a machine with normal internet access:', '',
  '```', 'npm run verify-sources      # opens each page, checks the quoted evidence and the number, flags hedges', 'npm run review              # regenerates this file', 'npm run validate            # production gate (needs ≥ 300 verified)', '```', '',
  'PDF sources need `pdftotext` (poppler-utils) installed. The script never promotes an entry whose page hedges the',
  'number, lacks the quoted wording, or shows a different value.', '');

const groups = new Map();
for (const e of unchecked) {
  if (!groups.has(code(e))) groups.set(code(e), []);
  groups.get(code(e)).push(e);
}
const ORDER = ['CONFLICT', 'HEDGED', 'VALUE_MISMATCH', 'NOT_FOUND', 'UNREACHABLE', 'NOT_OPENED'];
const EXPLAIN = {
  CONFLICT: 'The source (or the same publisher) gives different figures. Pick one or drop the entry.',
  HEDGED: 'The page hedges the number ("about", "nearly", "~"). Not allowed in production unless a precise figure is found.',
  VALUE_MISMATCH: 'The card value is not a number on the page.',
  NOT_FOUND: 'The quoted evidence was not found on the opened page.',
  UNREACHABLE: 'The page could not be opened.',
  NOT_OPENED: 'Source page not opened yet (network-blocked environment). Value and wording come from an official-domain search excerpt; `npm run verify-sources` will check them.',
};
out.push('## Not yet checked against the source page', '');
for (const key of [...ORDER, ...[...groups.keys()].filter((k) => !ORDER.includes(k))]) {
  const list = groups.get(key);
  if (!list) continue;
  out.push(`### ${key} (${list.length})`, '', EXPLAIN[key] || '', '');
  out.push('| id | category | card text | value | year | source | evidence (quoted) | reason / notes |', '|---|---|---|---|---|---|---|---|');
  for (const e of list.sort((a, b) => (a.category + a.id < b.category + b.id ? -1 : 1))) {
    const reason = key === 'NOT_OPENED' ? '' : e.reviewReason.replace(/^[A-Z_]+:\s*/, '');
    out.push(`| ${e.id} | ${CATEGORIES[e.category].label} | ${esc(e.text)} | ${e.value}% | ${e.year} | ${link(e)} | ${esc(e.evidence)} | ${esc([reason, e.notes].filter(Boolean).join(' — '))} |`);
  }
  out.push('');
}

out.push('## Spot-check sample (10%)', '');
if (verified.length) {
  out.push(`A seeded random 10% of the ${verified.length} verified entries, PDF sources first. Open each link and confirm the number, definition, population and year.`, '');
  out.push('| id | card text | value | year | source | evidence | verified on |', '|---|---|---|---|---|---|---|');
  for (const e of sample(verified, 0.1, `review:${verified.length}`)) {
    out.push(`| ${e.id} | ${esc(e.text)} | ${e.value}% | ${e.year} | ${link(e)} | ${esc(e.evidence)} | ${e.verifiedOn} |`);
  }
} else {
  out.push('No entry is verified yet, so there is nothing to sample. As a head start, here is a seeded 10% of the **candidates**',
    '(PDF sources first) that the founder can check by hand while network access is being arranged:', '');
  out.push('| id | card text | value | year | source | evidence |', '|---|---|---|---|---|---|');
  for (const e of sample(unchecked, 0.1, `candidates:${unchecked.length}`)) {
    out.push(`| ${e.id} | ${esc(e.text)} | ${e.value}% | ${e.year} | ${link(e)} | ${esc(e.evidence)} |`);
  }
}
out.push('');

out.push('## Unreachable sources log', '');
const unreachable = Object.entries(log).filter(([, v]) => v.result === 'UNREACHABLE');
out.push('- 2026-10-22, research environment: **all** source hosts unreachable (egress proxy allowed only package registries; page fetcher failed DNS for every domain, e.g. bls.gov, worldbank.org, ec.europa.eu, istat.it, ons.gov.uk, census.gov, nasa.gov, iucnredlist.org, who.int).');
for (const [id, v] of unreachable) out.push(`- ${v.checkedOn}: \`${id}\` ${v.url} (${v.detail})`);
out.push('');

writeFileSync(join(ROOT, 'DATA_REVIEW.md'), `${out.join('\n')}\n`);
console.log(`DATA_REVIEW.md written: ${verified.length} verified, ${approved.length} approved, ${unverified.length} unverified`);
